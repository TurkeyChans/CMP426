public class Person {

    private String name;
    private int age;
    private String ssn;
    private String address;
    public Person() {
        name = "";
        age = 0;
        ssn = "";
        address = "";
    }
    public Person(String name, int age, String ssn, String address) {
        this.name = name;
        this.age = age;
        this.ssn = ssn;
        this.address = address;
    }
    
    
}